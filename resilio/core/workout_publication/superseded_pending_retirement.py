"""Stable authority and identity proof for renderer-superseded retirement."""

from resilio.core.repository import RepositoryIO
from resilio.core.workout_publication.authority_matching import (
    publication_record_has_retained_workout_authority,
)
from resilio.core.workout_publication.identity_discovery import (
    discover_pending_owned_identity_matches,
)
from resilio.core.workout_publication.manifest import load_manifest
from resilio.core.workout_publication.policy import PublicationSafetyError
from resilio.core.workout_publication.retained_authority import (
    RetainedPublicationAuthority,
)
from resilio.integrations.intervals_icu.client import IntervalsIcuClient
from resilio.integrations.intervals_icu.dto import EventDTO
from resilio.schemas.publication import PendingWorkoutPublication


def prepare_renderer_superseded_pending_retirement(
    repo: RepositoryIO,
    client: IntervalsIcuClient,
    authority: RetainedPublicationAuthority,
) -> tuple[PendingWorkoutPublication, list[EventDTO]]:
    """Resolve pending-only ownership without certifying old generated bytes."""
    authoritative_workout = authority.workout
    local_workout_id = authoritative_workout.identity.local_workout_id
    manifest = load_manifest(repo)
    pending = manifest.pending.get(local_workout_id)
    if pending is None or manifest.workouts.get(local_workout_id) is not None:
        raise PublicationSafetyError(
            "Renderer-superseded retirement requires one pending-only ownership record"
        )
    if not publication_record_has_retained_workout_authority(
        pending,
        authoritative_workout,
    ):
        raise PublicationSafetyError(
            "Renderer-superseded pending publication lacks retained workout authority"
        )
    matches = discover_pending_owned_identity_matches(
        client,
        pending,
        athlete_id=client.get_athlete().id,
    )
    return pending, matches
